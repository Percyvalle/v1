"""Где лежит рабочее состояние бота.

Раньше состояние лежало прямо в корне проекта, вперемешку с исходниками:
bot.db, usage.json, voice_input.txt, logs/, bot.pid — рядом с main.py и
пакетом bot/. Работало, но давало два неприятных свойства.

Первое: каталог проекта переставал быть «только код». Резервная копия,
очистка перед чистым запуском, ответ на вопрос «что тут вообще данные, а
что исходники» — всё требовало знания списка имён файлов.

Второе, и оно уже стреляло: пути к состоянию совпадали с путями к коду, и
это совпадение молча закладывалось в код. Когда панель переехала в
apps/panel, выяснилось, что `Path(__file__).parent.parent` в разных местах
означал то корень проекта, то место .env, то место БД — и разошлось это
всё только при переезде (см. apps/panel/panel/paths.py).

Пути абсолютные, а не относительные cwd, как было до этого: bot.db
открывался как "bot.db", то есть зависел от того, из какой папки запущен
процесс. Панель запускает main.py с cwd=apps/twitch-bots и полагалась
на это; из любой другой папки тот же код создал бы новую пустую БД
вместо существующей.
"""

from __future__ import annotations

from pathlib import Path

# bot/paths.py -> bot -> apps/twitch-bots -> apps -> корень репозитория
REPO_ROOT = Path(__file__).resolve().parents[3]

VAR = REPO_ROOT / "var" / "twitch-bots"

LOGS = VAR / "logs"

# pid- и lock-файлы запущенных процессов. Отдельно от логов и БД: это
# самое эфемерное состояние, единственное, которое можно снести целиком
# на остановленной системе без последствий.
RUN = VAR / "run"

# Рабочие файлы экрана ботов в панели (история каналов, история промтов).
# Лежат здесь, а не рядом с панелью, потому что описывают состояние ИМЕННО
# этого бота и его профилей.
PANEL_STATE = VAR / "panel_state"


def ensure_dirs() -> None:
    """Создаёт каталоги состояния. Зовётся при старте процессов и из
    панели перед записью — на чистом клоне var/ не существует вовсе, он
    целиком в .gitignore."""
    for path in (VAR, LOGS, RUN, PANEL_STATE):
        path.mkdir(parents=True, exist_ok=True)
